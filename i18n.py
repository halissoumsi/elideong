from urllib.parse import quote
from flask import request, session, g

SUPPORTED_LANGUAGES = ('fr', 'en')
DEFAULT_LANGUAGE = 'fr'
LANG_COOKIE_NAME = 'elide_lang'


def get_current_lang() -> str:
    """Détermine la langue active (paramètre URL > cookie/session > français par défaut)."""
    cached = getattr(g, 'current_lang', None)
    if cached in SUPPORTED_LANGUAGES:
        return cached

    arg_lang = (request.args.get('lang') or '').strip().lower()
    if arg_lang in SUPPORTED_LANGUAGES:
        g.current_lang = arg_lang
        g.persist_lang_cookie = arg_lang
        return arg_lang

    cookie_lang = (request.cookies.get(LANG_COOKIE_NAME) or '').strip().lower()
    if cookie_lang in SUPPORTED_LANGUAGES:
        g.current_lang = cookie_lang
        return cookie_lang

    sess_lang = (session.get('lang') or '').strip().lower()
    if sess_lang in SUPPORTED_LANGUAGES:
        g.current_lang = sess_lang
        return sess_lang

    g.current_lang = DEFAULT_LANGUAGE
    return DEFAULT_LANGUAGE


def get_translations(lang: str = None) -> dict:
    """Retourne le dictionnaire de traductions pour la langue demandée."""
    code = lang if lang in SUPPORTED_LANGUAGES else get_current_lang()
    return TRANSLATIONS[code]


